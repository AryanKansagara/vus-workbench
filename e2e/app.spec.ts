test('the worklist searches, filters and pages with the keyboard', async ({ page }) => {
  await page.goto('/app?sample=synthetic-panel')
  const rows = page.locator('table.worklist tbody tr')
  await expect(rows).toHaveCount(15)
  await page.keyboard.press('/')
  await page.keyboard.type('splice donor')
  await expect(rows).toHaveCount(1)
  await page.getByPlaceholder('Gene, c., p., consequence').fill('')
  await page.locator('.filters select').first().selectOption('SYNG2')
  await expect(rows).toHaveCount(3)
  await page.locator('.filters select').nth(2).selectOption('curated')
  await expect(page.getByText('No variants match these filters.')).toBeVisible()
  await page.locator('.filters select').nth(2).selectOption('all')
  await rows.first().getByRole('link').first().click()
  const at = page.locator('.var-title')
  const first = await at.textContent()
  await page.locator('body').press(']')
  await expect(at).not.toHaveText(first!)
  await page.locator('body').press('[')
  await expect(at).toHaveText(first!)
})

test('curation: evidence, criteria, notes and status are logged with the editor and survive a reload', async ({ page }) => {
  await page.goto('/settings')
  await page.getByLabel(/Your name/).fill('Curator One')
  await page.getByLabel(/Laboratory or group/).fill('Lab "One", Unit 2')
  await miniHgvs(page, ['MINI,c.31C>T,'])
  await openVariant(page, 'c.31C>T')
  const score = page.locator('.sticky')
  await expect(score).toContainText('0 pts')
  await page.getByLabel('REVEL').fill('0.8')
  await page.getByLabel('REVEL').press('Enter')
  await expect(score).toContainText('+2 pts') // PP3_Moderate
  await page.getByRole('button', { name: 'Show all 26 criteria to add one' }).click()
  const ps3 = page.locator('.crit-row').filter({ hasText: 'PS3' })
  await ps3.getByRole('checkbox').click() // the box follows the saved worklist, so it is not ticked synchronously
  await expect(score).toContainText('+6 pts')
  await expect(score).toContainText('Likely pathogenic')
  await page.getByLabel('PS3 strength').selectOption('Moderate')
  await expect(score).toContainText('+4 pts')
  await page.getByLabel('Curator note').fill('Segregation pending')
  await page.getByLabel('Curator note').blur()
  await expect(page.locator('.audit')).toContainText('Segregation pending')
  await page.locator('.var-head').getByLabel('Status').selectOption('curated')
  await expect(page.locator('.audit')).toContainText('Marked curated')
  await page.reload()
  await expect(score).toContainText('+4 pts')
  await expect(page.locator('.audit li')).toHaveCount(5)
  await expect(page.locator('.audit')).toContainText('Curator One')
  // 0 > 2 is VUS throughout; 2 > 6 is a reclassification and 6 > 4 goes back.
  await expect(page.locator('.timeline li')).toHaveCount(3)
  await expect(page.locator('.var-head').getByLabel('Status')).toHaveValue('curated')

  await page.getByRole('link', { name: 'Curation report' }).click()
  const sheet = page.locator('.sheet')
  await expect(sheet).toContainText('Research use only')
  await expect(sheet).toContainText('4 points (warm), posterior probability 67.5%') // 350^0.5 = 18.71; 1.871 / 2.771
  await expect(sheet).toContainText('Lab "One", Unit 2')
  await expect(sheet).toContainText('Segregation pending')
})

