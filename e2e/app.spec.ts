test('lab discrepancies: severity, own-criteria totals and the reconciliation CSV', async ({ page }) => {
  await page.goto('/app?sample=lab-discrepancy&tab=labs')
  // PVS1 + PM2 = 9 (LP) vs a Pathogenic call; BS1 + BS3 + BP5 = -9.
  const card = page.locator('.disc').filter({ hasText: 'BRCA2:c.9976A>T' })
  await expect(card).toContainText('Major (P/LP vs B/LB)')
  await expect(card).toContainText("Synthetic Lab A's own criteria total 9 points (Likely pathogenic), not Pathogenic.")
  await page.getByRole('button', { name: /^Confidence difference/ }).click()
  // CFTR: PS3 4 + PM3_VeryStrong 8 + PM4 2 = 14 (P); PS3 4 + PM4 2 = 6 (LP). Both labs agree with their own totals.
  await expect(page.locator('.disc')).toHaveCount(1)
  await expect(page.locator('.disc')).toContainText('CFTR:c.1521_1523del')
  const [name, csv] = await saveAs(page, page.getByRole('button', { name: 'Reconciliation CSV' }))
  expect(name).toBe('brca1-2-and-cftr-lab-discrepancies-lab-reconciliation.csv')
  const rows = cells(csv)
  expect(rows).toHaveLength(14)
  const a = rows.find((r) => r[0] === 'CFTR:c.1521_1523del' && r[2] === 'Synthetic Lab A')!
  expect(a.slice(3, 8)).toEqual(['Pathogenic', 'PS3 PM3_VeryStrong PM4', '14', 'Pathogenic', ''])
})

