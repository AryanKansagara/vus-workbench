test('worklist and curated CSVs carry the shown values, and the curated file imports as a lab table', async ({ page }) => {
  await miniHgvs(page, ['MINI,c.11G>A,0', 'MINI,c.31C>T,0.0004'])
  const [, csv] = await saveAs(page, page.getByRole('button', { name: 'Worklist CSV' }))
  const rows = cells(csv)
  const o = Object.fromEntries(rows[0].map((h, i) => [h, rows[1][i]]))
  expect(o).toMatchObject({ gene: 'MINI', transcript: 'NM_900001.1', hgvs_c: 'c.11G>A', hgvs_p: 'p.(Trp4Ter)', chrom: 'chr9', pos: '1026', ref: 'G', alt: 'A', criteria: 'PVS1 PM2', points: '9', classification: 'Likely pathogenic', status: 'new', source: 'list.csv:2' })
  await page.getByRole('button', { name: 'Curated calls CSV' }).click()
  await toastText(page, 'Nothing is marked curated yet')
  await openVariant(page, 'c.11G>A')
  await page.locator('.var-head').getByLabel('Status').selectOption('curated')
  await expect(page.locator('.audit')).toContainText('Marked curated')
  await tab(page, 'Worklist')
  const [, curated] = await saveAs(page, page.getByRole('button', { name: 'Curated calls CSV' }))
  expect(cells(curated)[1].slice(0, 6)).toEqual(['NM_900001.1(MINI):c.11G>A', 'MINI', 'My lab', 'Likely pathogenic', 'PVS1, PM2', '9'])
  await importFile(page, 'other-lab.csv', curated)
  const card = page.locator('.disc')
  await expect(card).toContainText('MINI:c.11G>A')
  // Lab column and "This worklist" column both total 9.
  await expect(card.locator('tr.sum td')).toHaveText(['Points', '9', '9'])
})

