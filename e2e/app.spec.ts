test('Ensembl and ClinVar lookups run only on request, and a blocked service gives a message', async ({ page, onRequest }) => {
  await page.goto('/app?sample=lab-discrepancy&tab=genes')
  await expect(page.getByRole('heading', { name: 'Transcript models' })).toBeVisible()
  expect(onRequest).toEqual([])
  await page.getByLabel('Gene symbol').fill('BRCA2')
  await page.getByRole('button', { name: 'Load from Ensembl' }).click()
  await toastText(page, 'Could not reach rest.ensembl.org')
  await tab(page, 'Lab discrepancies')
  await page.getByRole('button', { name: /^Fetch ClinVar submissions/ }).click()
  await toastText(page, 'Could not reach NCBI E-utilities')
  expect([...new Set(onRequest)].sort()).toEqual(['eutils.ncbi.nlm.nih.gov', 'rest.ensembl.org'])
})
